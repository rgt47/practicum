#!/usr/bin/env python3
"""Generate analysis/report/contents.qmd, the HTML book's full contents.

Run as a Quarto pre-render step, so the page always follows the chapter
order in _quarto.yml. Chapter numbers are computed the way Quarto
assigns them (numbered chapters 1, 2, ...; numbered appendices A, B,
...; parts I, II, ...). Each chapter's one-line summary is the bullet
that describes it on its part page ('- @sec-why distinguishes ...').

The page is HTML only: the PDF has its own printed table of contents.
If PyYAML is unavailable the script leaves the existing page in place
rather than failing the build.
"""
import re
import sys
import textwrap
from pathlib import Path

REPORT = Path(__file__).resolve().parent.parent / 'analysis' / 'report'
OUT = REPORT / 'contents.qmd'

try:
    import yaml
except ImportError:
    print('make-contents: PyYAML not available; keeping existing '
          'contents.qmd', file=sys.stderr)
    sys.exit(0)

ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X',
         'XI', 'XII']


def heading(qmd):
    """Title, anchor id, and numbered/listed flags of a file's H1."""
    for line in (REPORT / qmd).read_text().splitlines():
        m = re.match(r'^#\s+(.*?)\s*(\{[^}]*\})?\s*$', line)
        if m:
            attrs = m.group(2) or ''
            sid = re.search(r'#(sec-[\w-]+)', attrs)
            return (m.group(1), sid.group(1) if sid else None,
                    '.unnumbered' not in attrs, '.unlisted' not in attrs)
    return qmd, None, False, False


def summaries(part_qmd):
    """Map sec-id -> summary text from a part page's bullets."""
    out = {}
    text = (REPORT / part_qmd).read_text()
    for m in re.finditer(r'^- @(sec-[\w-]+) (.*?)(?=\n- |\n\n|\Z)',
                         text, re.M | re.S):
        s = ' '.join(m.group(2).split())
        out[m.group(1)] = s[0].upper() + s[1:]
    return out


def entry(qmd, number, summary=None):
    title, _, _, _ = heading(qmd)
    label = f'{number} {title}' if number else title
    line = f'- [{label}]({qmd})'
    if summary:
        line += '\\\n' + textwrap.fill(summary, width=72,
                                        initial_indent='  ',
                                        subsequent_indent='  ')
    return line


book = yaml.safe_load((REPORT / '_quarto.yml').read_text())['book']
lines = []
chap = 0
part_no = 0


def add_chapter(qmd, summ=None):
    global chap
    if qmd == 'contents.qmd':
        return
    title, sid, numbered, listed = heading(qmd)
    if not listed:
        return
    num = None
    if numbered:
        chap += 1
        num = str(chap)
    lines.append(entry(qmd, num, (summ or {}).get(sid)))


back_matter_open = False
for item in book['chapters']:
    if isinstance(item, str):
        # Top-level files after the parts (References) are back matter,
        # not part of the last part.
        if part_no and not back_matter_open:
            lines.append('')
            lines.append('## References and Appendices {.unnumbered}')
            lines.append('')
            back_matter_open = True
        add_chapter(item)
    else:
        part_no += 1
        ptitle, _, _, _ = heading(item['part'])
        lines.append('')
        lines.append(f'## Part {ROMAN[part_no - 1]}. '
                     f'[{ptitle}]({item["part"]}) {{.unnumbered}}')
        lines.append('')
        summ = summaries(item['part'])
        for c in item['chapters']:
            add_chapter(c, summ)

if not back_matter_open:
    lines.append('')
    lines.append('## Appendices {.unnumbered}')
    lines.append('')
app = 0
for qmd in book.get('appendices', []):
    title, sid, numbered, listed = heading(qmd)
    if not listed:
        continue
    num = None
    if numbered:
        num = chr(ord('A') + app)
        app += 1
    lines.append(entry(qmd, num))

body = '\n'.join(lines).strip('\n')
page = f'''::: {{.content-visible when-format="html"}}

# Contents {{.unnumbered}}

<!-- Generated by tools/make-contents.py from _quarto.yml and the part
pages on every build. Edit those, not this file. -->

Every part and chapter of the book, in reading order, with the
one-line summary from each part's opening page.

{body}

:::
'''
if not OUT.exists() or OUT.read_text() != page:
    OUT.write_text(page)
    print(f'make-contents: wrote {OUT.name}')
