# Writes the default HF-HOME running-study dataset and its codebook.
# Run from the repository root:
#   Rscript analysis/scripts/make_hfhome.R
# Every number in the codebook is computed from the generated data
# (house rule 13), so rerunning this script keeps the two in step.

source(file.path('R', 'hfhome.R'))

out_dir <- file.path('analysis', 'data', 'raw_data', 'hfhome')
hf <- hfhome_generate()
paths <- hfhome_write(out_dir, data = hf)

o <- hf$outcomes
arm <- hf$randomization$arm
stopifnot(nrow(o) == nrow(hf$demographics),
          identical(o$patient_id, hf$randomization$patient_id))

pct <- function(x, digits = 1) sprintf(paste0('%.', digits, 'f%%'),
                                       100 * x)
fmt <- function(x) format(x, big.mark = ',', trim = TRUE)
rate <- tapply(o$event_30d, arm, mean, na.rm = TRUE)
n_obs <- tapply(!is.na(o$event_30d), arm, sum)
hh7 <- with(hf$visits, unique(patient_id[visit_type == 'home_health' &
                                           visit_day <= 7]))
got_hh <- tapply(hf$randomization$patient_id %in% hh7, arm, mean)
key <- c('visit_id', 'test_code')
n_dup <- sum(duplicated(hf$labs[key]))
orphans <- setdiff(hf$labs$patient_id, hf$demographics$patient_id)
file_rows <- vapply(hf, nrow, integer(1))

file_table <- paste0(
  '| `', names(hf), '.csv` | ', fmt(file_rows), ' |',
  collapse = '\n'
)

codebook <- c(
  '# HF-HOME synthetic trial: raw exports and codebook',
  paste0('*', format(Sys.time(), '%Y-%m-%d %H:%M %Z'), '*'),
  '',
  'Generated by `analysis/scripts/make_hfhome.R`, which calls',
  '`hfhome_generate()` (package `practicum`, file `R/hfhome.R`) with',
  'its defaults: `n_per_arm = 1216`, `seed = 20260423`, `messy = TRUE`.',
  'Do not edit these files by hand; rerun the script. Every number',
  'below is computed by the script from the data it wrote.',
  '',
  'All people, identifiers, and events are synthetic. Names are',
  'random combinations from short lists, MRNs carry the prefix',
  '`SYN-`, and telephone numbers use the fictional 555-01xx exchange.',
  'ZIP codes are real codes, so that de-identification exercises',
  'behave as they would on real data.',
  '',
  '## Design',
  '',
  'The trial follows SAP v1.0 in the analysis-plan chapter: 1:1',
  'randomization to home-health visits within 7 days of discharge or',
  'usual care, stratified by site and ejection-fraction stratum',
  '(permuted blocks of 4), primary outcome readmission or death within',
  '30 days of index discharge (composite; death is an event), analyzed',
  'as randomized (treatment policy).',
  '',
  paste0('- Randomized: ', fmt(nrow(o)), ' (',
         fmt(sum(arm == 'Usual care')), ' usual care, ',
         fmt(sum(arm == 'Home health')), ' home health).'),
  paste0('- Outcome model calibrated to marginal risks of 25% (usual ',
         'care) and 20% (home health).'),
  paste0('- Observed in this draw: ', pct(rate[['Usual care']]),
         ' usual care (', fmt(n_obs[['Usual care']]), ' ascertained), ',
         pct(rate[['Home health']]), ' home health (',
         fmt(n_obs[['Home health']]), ' ascertained).'),
  paste0('- Unascertained outcomes: ', fmt(sum(!o$ascertained)), ' (',
         pct(mean(!o$ascertained)), '), driven by out-of-state',
         ' addresses and unrelated to the outcome.'),
  paste0('- Home-health visit within 7 days: ',
         pct(got_hh[['Home health']]), ' of the home-health arm, ',
         pct(got_hh[['Usual care']]), ' of the usual-care arm.'),
  '',
  '## Files',
  '',
  '| File | Rows |',
  '|---|---|',
  file_table,
  '',
  'All files are UTF-8 with dates as `YYYY-MM-DD` and missing values as',
  'empty fields, except `crf_export.csv` (see Planted pathologies).',
  '',
  '## Tables and columns',
  '',
  '### `demographics.csv` (one row per patient; contains identifiers)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Four-digit study ID with leading zeros (`0001`). Key for every table. |',
  '| `mrn` | character | Synthetic medical record number, `SYN-` plus 7 digits. Direct identifier. |',
  '| `first_name`, `last_name` | character | Synthetic names; some carry accents (UTF-8). Direct identifiers. |',
  '| `dob` | date | Date of birth. Identifier under Safe Harbor (keep year only). |',
  '| `age` | integer | Age in whole years at index discharge; some patients are over 89. |',
  '| `sex` | character | `F` or `M`. |',
  '| `race` | character | Self-reported race (OMB categories, plus `Multiple`, `Not reported`). |',
  '| `ethnicity` | character | `Hispanic or Latino`, `Not Hispanic or Latino`, `Not reported`. |',
  '| `zip` | character | Five-digit ZIP code. San Diego area, or out of state for movers; some begin with `0`. |',
  '| `phone` | character | Fictional telephone number. Direct identifier. |',
  '',
  '### `randomization.csv` (one row per patient)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Study ID. |',
  '| `site` | character | `Site A` to `Site E`. Stratification factor. |',
  '| `ef_stratum` | character | `Reduced EF` (ejection fraction below 40%) or `Preserved EF`. Stratification factor. |',
  '| `rand_seq` | integer | Sequence number within the site by EF stratum. |',
  '| `rand_date` | date | Randomization date; equal to the index discharge date. |',
  '| `arm` | character | `Usual care` or `Home health` (a factor in R, levels in that order). |',
  '',
  '### `baseline.csv` (one row per patient)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Study ID. |',
  '| `discharge_date` | date | Index discharge date, 2024-02-01 to 2025-11-30. Day 0. |',
  '| `ef_pct` | integer | Baseline left-ventricular ejection fraction, percent. SAP covariate. |',
  '| `discharge_med_count` | integer | Number of discharge medications; equals the patient\'s rows in `medications.csv`. SAP covariate. |',
  paste0('| `sbp_discharge` | integer | Systolic blood pressure at ',
         'discharge, mmHg. Missing for ',
         fmt(sum(is.na(hf$baseline$sbp_discharge))), ' patients. |'),
  paste0('| `weight_kg` | numeric | Weight at discharge, kg. Missing for ',
         fmt(sum(is.na(hf$baseline$weight_kg))), ' patients. |'),
  '',
  '### `visits.csv` (one row per contact)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `visit_id` | character | `<patient_id>-<nn>`, numbered in date order within patient; `-01` is always discharge. |',
  '| `patient_id` | character | Study ID. |',
  '| `visit_type` | character | `discharge` (day 0), `home_health`, or `clinic_day30` (days 28 to 35). |',
  '| `visit_day` | integer | Days since index discharge. |',
  '| `visit_date` | date | Calendar date of the contact. |',
  '',
  'Home-health visits occur in both arms (nonadherence in both',
  'directions): most home-health patients have a first visit on days',
  '1 to 7, some have none or a late first visit (days 8 to 14), and a',
  'few usual-care patients receive home health outside the protocol.',
  'No visit is recorded on or after a readmission or death, so a',
  'patient whose event preceded the planned visit appears unexposed:',
  'the immortal-time trap of the intake chapter.',
  '',
  '### `labs.csv` (long format, one row per visit and test)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Study ID. |',
  '| `visit_id` | character | Visit at which the sample was drawn. |',
  '| `test_code` | character | `NTPROBNP`, `CREAT`, `K`, `SODIUM`, `HGB`. Discharge: all five; home health: `CREAT`, `K`; day-30 clinic: all but `HGB`. |',
  '| `value` | numeric | Result. |',
  '| `unit` | character | `pg/mL`, `mg/dL`, `mmol/L`, `mmol/L`, `g/dL` respectively. |',
  '',
  '### `medications.csv` (one row per discharge medication)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Study ID. |',
  '| `med_seq` | integer | Sequence within patient. |',
  '| `med_text` | character | Free-text dosing string as entered, for example `Furosemide 40 mg BID`, `carvedilol 6.25mg BID`, `Entresto 24-26 mg twice daily`, `digoxin 125 mcg QD`. |',
  '',
  'The strings mix generic and brand names, `mg` with and without a',
  'space, upper and lower case, frequency codes (`BID`, `b.i.d.`,',
  '`twice daily`, `qd`, `QAM`, `qhs`, `PRN`), combination doses',
  '(`49/51 mg`, `24-26 mg`), and units other than mg (`mcg`, `mEq`,',
  '`units`).',
  '',
  '### `outcomes.csv` (one row per patient)',
  '',
  '| Column | Type | Description |',
  '|---|---|---|',
  '| `patient_id` | character | Study ID. |',
  '| `ascertained` | logical | `FALSE` if the patient could not be linked to the state health-information exchange. |',
  '| `event_30d` | integer | Primary outcome: 1 if readmitted or dead within 30 days of discharge, 0 if neither, empty if unascertained. |',
  '| `first_event` | character | `readmission`, `death`, `none`, or empty if unascertained. |',
  '| `event_date` | date | Date of the first event. |',
  '| `days_to_event` | integer | Days from discharge to the first event (1 to 30). |',
  '| `readmit_date` | date | First readmission within 30 days (secondary outcome S1). |',
  '| `death_date` | date | Death within 30 days, including after a readmission. |',
  '',
  '### `crf_export.csv` (raw CRF export, all text, one row per patient)',
  '',
  'Columns: `patient_id`, `site`, `sex`, `dob`, `discharge_date`,',
  '`ef_pct`, `sbp_discharge`, `weight_kg`. The same patients and',
  'values as the clean tables, written the way five site systems',
  'export them.',
  '',
  '## Planted pathologies',
  '',
  '| Pathology | Where | Chapter |',
  '|---|---|---|',
  '| UTF-8 byte-order mark and CRLF line endings | `crf_export.csv` | Acquisition (12b) |',
  '| Leading-zero IDs lost at one site (`7` for `0007`) | `crf_export.csv`, Site E | Acquisition (12b), joins (15) |',
  '| Leading-zero IDs and ZIP codes that an unspecified `read.csv()` turns into integers | every file | Acquisition (12b) |',
  '| Date formats by site: `YYYY-MM-DD` (A, B), `MM/DD/YYYY` (C), `DD-MON-YYYY` (D), `YYYYMMDD` (E) | `crf_export.csv` | Acquisition (12b), types (14) |',
  '| Sex coded `F`/`M` (A, E), `Female`/`Male` (B), `f`/`m` (C), `2`/`1` (D) | `crf_export.csv` | Wrangling (13), types (14) |',
  '| Site labels varying in case and leading or trailing spaces | `crf_export.csv` | Acquisition (12b), wrangling (13) |',
  '| Missing numbers as an empty field (A, C), `NA` (B, E), and `-99` (D) | `crf_export.csv` | Acquisition (12b), missing data (17) |',
  paste0('| Duplicated visit-test rows (', n_dup, '): one exact ',
         'duplicate of a discharge `NTPROBNP`, one discharge `K` ',
         're-run with a different value | `labs.csv` | Joins (15) |'),
  paste0('| Orphan lab patient never randomized (`',
         paste(orphans, collapse = '`, `'),
         '`) | `labs.csv` | Joins (15) |'),
  '| Free-text dosing strings | `medications.csv` | Types (14) |',
  '| Direct identifiers, ages over 89, ZIP prefixes on the HHS restricted list (036, 059, 821; verify against current Census data) | `demographics.csv` | De-identification (02b) |',
  '| Event before planned visit erases the visit | `visits.csv` | Team science intake (03), analysis plan (18) |',
  '',
  '## Reading the files',
  '',
  '```r',
  "hf_dir <- file.path('analysis', 'data', 'raw_data', 'hfhome')",
  'demographics <- readr::read_csv(',
  "  file.path(hf_dir, 'demographics.csv'),",
  "  col_types = readr::cols(patient_id = 'c', zip = 'c',",
  "                          dob = 'D', .default = '?')",
  ')',
  '```',
  '',
  'Or regenerate the same data in memory with',
  '`practicum::hfhome_generate()`, and SDTM-like DM, EX, and DS',
  'domains with `practicum::hfhome_sdtm()`.'
)

writeLines(codebook, file.path(out_dir, 'README.md'), useBytes = TRUE)
message('Wrote ', length(paths), ' CSV files and README.md to ', out_dir)
